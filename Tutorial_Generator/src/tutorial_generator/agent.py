import json
import re

from agents import Agent, Runner
from openai import OpenAI

from tutorial_generator.config import Settings
from tutorial_generator.document import parse_diagram
from tutorial_generator.prompts import TUTORIAL_AGENT_INSTRUCTIONS
from tutorial_generator.research import (
    ResearchResult,
    Source,
    research_topic,
    validate_learning_goal,
    validate_topic,
)

MAX_AGENT_TURNS = 4
MAX_TUTORIAL_LENGTH = 36_000
MIN_TUTORIAL_WORDS = 350
MIN_TUTORIAL_PROSE_WORDS = 200
REQUIRED_TUTORIAL_SECTIONS = (
    "in simple words",
    "imagine it this way",
    "how it works",
    "example",
    "visual overview",
    "when it is useful",
    "one limitation",
    "quick recap",
)


def _section_prose_word_count(markdown: str) -> int:
    prose_word_count = 0
    in_code_block = False
    for line in markdown.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            in_code_block = not in_code_block
            continue
        if in_code_block or not stripped:
            continue
        if re.match(r"^#{1,3}\s+", stripped):
            continue
        if re.match(r"^(?:[-*+]\s+|\d+[.)]\s+)", stripped):
            continue
        prose_word_count += len(re.findall(r"\b[\w'-]+\b", stripped))
    return prose_word_count


def validate_tutorial_content(markdown: str, sources: tuple[Source, ...]) -> None:
    headings = {
        match.group(1).strip().casefold()
        for match in re.finditer(r"(?m)^#{1,3}\s+(.+?)\s*#*\s*$", markdown)
    }
    missing_sections = [
        section for section in REQUIRED_TUTORIAL_SECTIONS if section not in headings
    ]
    interview_sections = [
        heading
        for heading in headings
        if "interview" in heading and ("question" in heading or "practice" in heading)
    ]
    if interview_sections:
        raise RuntimeError(
            "Interview questions and answers are generated by a separate feature."
        )
    if missing_sections:
        raise RuntimeError(
            "The tutorial is missing required teaching sections: "
            + ", ".join(missing_sections)
        )

    word_count = len(re.findall(r"\b[\w'-]+\b", markdown))
    if word_count < MIN_TUTORIAL_WORDS:
        raise RuntimeError(
            f"The tutorial is too short ({word_count} words); "
            f"at least {MIN_TUTORIAL_WORDS:,} words are required "
            "for a detailed lesson."
        )
    prose_word_count = _section_prose_word_count(markdown)
    if prose_word_count < MIN_TUTORIAL_PROSE_WORDS:
        raise RuntimeError(
            "The tutorial does not explain the "
            f"topic in enough prose ({prose_word_count} words; at least "
            f"{MIN_TUTORIAL_PROSE_WORDS} are required)."
        )
    diagram = re.search(
        r"(?ms)^```diagram[ \t]*\r?\n(.*?)\r?\n^```[ \t]*$",
        markdown,
    )
    if diagram is None or parse_diagram(diagram.group(1).strip()) is None:
        raise RuntimeError("The tutorial agent did not include a valid flow diagram.")

    citations = [int(number) for number in re.findall(r"(?<!\w)\[(\d+)\]", markdown)]
    if not citations:
        raise RuntimeError("The tutorial agent did not cite its research inline.")
    if any(number < 1 or number > len(sources) for number in citations):
        raise RuntimeError("The tutorial agent returned an invalid source citation.")


def _research_context(result: ResearchResult) -> str:
    return json.dumps(
        {
            "research": result.notes,
            "sources": [
                {"number": index, "title": source.title, "url": source.url}
                for index, source in enumerate(result.sources, start=1)
            ],
        },
        ensure_ascii=False,
    )


def generate_tutorial(
    client: OpenAI,
    settings: Settings,
    topic: str,
    learning_goal: str = "",
) -> tuple[str, tuple[Source, ...]]:
    normalized_topic = validate_topic(topic)
    normalized_goal = validate_learning_goal(learning_goal)
    research = research_topic(
        client=client,
        settings=settings,
        topic=normalized_topic,
        learning_goal=normalized_goal,
    )

    agent = Agent(
        name="Tutorial Generator",
        instructions=TUTORIAL_AGENT_INSTRUCTIONS,
        model=settings.model,
    )
    task = json.dumps(
        {
            "topic": normalized_topic,
            "learning_goal": normalized_goal,
            "verified_web_research": json.loads(_research_context(research)),
        },
        ensure_ascii=False,
    )
    result = Runner.run_sync(agent, task, max_turns=MAX_AGENT_TURNS)
    tutorial = result.final_output
    if not isinstance(tutorial, str) or not tutorial.strip():
        raise RuntimeError("The tutorial agent returned an empty document.")
    tutorial = tutorial.strip()
    if len(tutorial) > MAX_TUTORIAL_LENGTH:
        raise RuntimeError("The tutorial agent returned a document that is too long.")

    sources = research.sources
    try:
        validate_tutorial_content(tutorial, sources)
    except RuntimeError as error:
        citation_error = str(error)
        if citation_error not in {
            "The tutorial agent did not cite its research inline.",
            "The tutorial agent returned an invalid source citation.",
        }:
            raise

        repair_task = (
            f"{task}\n\n"
            "Your previous tutorial draft did not pass citation validation. "
            "Rewrite the complete tutorial, preserving the clear beginner "
            "explanation and all required sections. Add a numeric citation "
            "such as [1] next to every factual paragraph, using only the "
            "numbered sources in the verified_web_research in your task. "
            "Do not invent source numbers. Ensure every citation number maps "
            "to the correct source. "
            f"Validation feedback: {citation_error}\n\n"
            f"Previous draft:\n{tutorial}"
        )
        result = Runner.run_sync(agent, repair_task, max_turns=MAX_AGENT_TURNS)
        repaired_tutorial = result.final_output
        if not isinstance(repaired_tutorial, str) or not repaired_tutorial.strip():
            raise RuntimeError("The tutorial agent returned an empty document.")
        tutorial = repaired_tutorial.strip()
        if len(tutorial) > MAX_TUTORIAL_LENGTH:
            raise RuntimeError("The tutorial agent returned a document that is too long.")
        validate_tutorial_content(tutorial, sources)
    return tutorial, sources
